#ifndef ANSI_COLORS_H
#define ANSI_COLORS_H

/* ANSI color codes. Each section of the program uses its own color. */
#define ANSI_RESET "\033[0m"
#define ANSI_MENU "\033[36m"
#define ANSI_PROMPT "\033[33m"
#define ANSI_INPUT "\033[35m"
#define ANSI_SUCCESS "\033[32m"
#define ANSI_ERROR "\033[91m"
#define ANSI_INFO "\033[94m"
#define ANSI_HEADER "\033[1;37;44m"
#define ANSI_ALERT_HEADER "\033[1;37;41m"
#define ANSI_NORMAL_STATUS "\033[1;32m"
#define ANSI_ALERT_STATUS "\033[1;91m"

#endif
